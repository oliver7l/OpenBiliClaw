def ts2sec(ts):
    h, m, rest = ts.split(":")
    return int(h) * 3600 + int(m) * 60 + float(rest.replace(",", "."))

def sec2ts(s):
    s = max(0.0, s)
    h = int(s // 3600); m = int(s % 3600 // 60); sec = s % 60
    return f"{h:02d}:{m:02d}:{sec:06.3f}".replace(".", ",")

def parse_srt(path):
    cues = []
    blocks = re.split(r"\n\s*\n", open(path, encoding="utf-8").read().strip())
    for b in blocks:
        lines = b.strip().splitlines()
        if len(lines) >= 2 and "-->" in lines[1]:
            t1, t2 = [x.strip().split(" --> ") for x in [lines[1]]][0]
            text = " ".join(l.strip() for l in lines[2:])
            cues.append((ts2sec(t1), ts2sec(t2), text))
    return cues

def missing_check(cues):
    miss = sorted({t for _,_,t in cues if t not in ZH})
    if miss:
        print("MISSING:", len(miss))
        for m in miss: print("  ", m)
    return miss

def write_clip_srt(cues, start, dur, out_path, skip_ivs=()):
    # whisper 在纯音乐段会硬编出不存在的歌词（片头/片尾主题曲），整体丢弃
    drop_ranges = [(0, 6.5), (1199, 1300)]
    lines, idx = [], 0
    for a, b, text in cues:
        ra, rb = a - start, b - start
        if rb <= 0 or ra >= dur:
            continue
        if any(a >= d0 and b <= d1 for d0, d1 in drop_ranges):
            continue
        # 卡片显示期间隐藏字幕：与弹卡窗口重叠的台词整条剔除
        if any(ra < e and rb > s for s, e in skip_ivs):
            continue
        ra, rb = max(ra, 0.0), min(rb, dur)
        zh = ZH.get(text, "")
        idx += 1
        lines.append(f"{idx}\n{sec2ts(ra)} --> {sec2ts(rb)}\n{text}\n{zh}\n")
    open(out_path, "w", encoding="utf-8").write("\n".join(lines))
    return idx

